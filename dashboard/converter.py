"""Turn approved test cases into a runnable PyTest file (tests/generated/test_generated_cases.py)."""
import json
import re
from pathlib import Path

from . import db

TARGET = db.ROOT / "tests" / "generated" / "test_generated_cases.py"

HEADER = '''"""AUTO-GENERATED by the QA dashboard from approved test cases. Re-generated on each conversion."""
import pytest

pytestmark = pytest.mark.api
'''


def _slug(text):
    return re.sub(r"[^a-z0-9]+", "_", text.lower()).strip("_")[:40] or "case"


def _block(c):
    meta = (f"@pytest.mark.case({c['tc_id']!r}, {c['scenario']!r}, expected={c['expected']!r}, "
            f"category='Generated', severity='Medium')")
    name = f"test_{_slug(c['tc_id'])}_{_slug(c['scenario'])}"
    spec = json.loads(c["api_spec"]) if c["api_spec"] else None
    if not spec:
        return (f"\n\n{meta}\ndef {name}():\n"
                f"    pytest.skip({('Skeleton only - implement UI steps for: ' + c['input'])!r})\n")
    call = f"client.{spec['method'].lower()}({spec['path']!r}"
    if spec.get("json") is not None:
        call += f", json={spec['json']!r}"
    call += ")"
    lines = [f"\n\n{meta}", f"def {name}(client):", f"    r = {call}",
             f"    assert r.status_code == {spec['status']}, f\"Expected HTTP {spec['status']} but got {{r.status_code}}\""]
    if "min_items" in spec:
        lines.append(f"    assert len(r.get_json()) >= {int(spec['min_items'])}, \"Too few items returned\"")
    if "max_items" in spec:
        lines.append(f"    assert len(r.get_json()) <= {int(spec['max_items'])}, \"Too many items returned\"")
    return "\n".join(lines) + "\n"


def convert(ids):
    """Marks selected approved cases as converted and rewrites the generated test file.
    Returns (executable, skeleton) counts."""
    for cid in ids:
        row = db.one("SELECT * FROM cases WHERE id=? AND approved=1", (cid,))
        if row:
            db.execute("UPDATE cases SET automated=? WHERE id=?", (1 if row["api_spec"] else 2, cid))
    rows = db.query("SELECT * FROM cases WHERE automated>0 ORDER BY id")
    seen, parts = set(), [HEADER]
    for c in rows:
        key = (c["tc_id"], c["scenario"])
        if key in seen:
            continue
        seen.add(key)
        parts.append(_block(c))
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text("".join(parts))
    return (sum(1 for c in rows if c["automated"] == 1), sum(1 for c in rows if c["automated"] == 2))
